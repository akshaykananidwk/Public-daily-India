"""તહેવાર કેલેન્ડર — આજે/આવતીકાલે કયો તહેવાર છે એ યાદ કરાવે.
(મુખ્ય ગુજરાતી/ભારતીય તહેવારો — વર્ષ પ્રમાણે તારીખ ઉમેરી શકાય.)
"""
from datetime import date, timedelta

# MM-DD : તહેવારનું નામ (નિશ્ચિત તારીખવાળા)
FIXED = {
    "01-01": "નૂતન વર્ષ (અંગ્રેજી)",
    "01-14": "મકર સંક્રાંતિ / ઉત્તરાયણ",
    "01-26": "પ્રજાસત્તાક દિન",
    "05-01": "ગુજરાત સ્થાપના દિન",
    "08-15": "સ્વતંત્રતા દિન",
    "10-02": "ગાંધી જયંતી",
    "12-25": "નાતાલ",
}

# વર્ષ પ્રમાણે બદલાતા તહેવારો (ચંદ્ર કેલેન્ડર) — તારીખ દર વર્ષે અપડેટ કરવી
MOVABLE = {
    "2026-08-15": "રક્ષાબંધન",
    "2026-08-16": "જન્માષ્ટમી",
    "2026-09-14": "ગણેશ ચતુર્થી",
    "2026-10-20": "નવરાત્રી શરૂ",
    "2026-10-29": "દશેરા",
    "2026-11-08": "દિવાળી",
    "2026-11-09": "નૂતન વર્ષ (ગુજરાતી)",
}


def festival_on(d: date) -> str:
    return MOVABLE.get(d.isoformat()) or FIXED.get(d.strftime("%m-%d"), "")


def upcoming(days: int = 2) -> list[dict]:
    """આજથી આગળના `days` દિવસના તહેવારો."""
    out = []
    today = date.today()
    for i in range(days + 1):
        d = today + timedelta(days=i)
        name = festival_on(d)
        if name:
            when = "આજે" if i == 0 else ("આવતીકાલે" if i == 1
                                          else d.strftime("%d-%m"))
            out.append({"date": d.isoformat(), "when": when, "name": name})
    return out
